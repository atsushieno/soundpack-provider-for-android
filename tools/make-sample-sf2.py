#!/usr/bin/env python3
"""Writes the tiny SoundFont 2 files used by samples/sample-sf2-pack.

    python3 tools/make-sample-sf2.py samples/sample-sf2-pack/src/main/assets/sf2

Each file holds one 16-bit mono sample, one instrument and the given presets, following the
SoundFont 2.04 layout (RIFF sfbk: INFO, sdta/smpl, pdta with all nine sub-chunks). The output
is deterministic, so the committed files can be regenerated and compared.
"""

import math
import struct
import sys
from pathlib import Path


def chunk(fourcc, payload):
    data = fourcc.encode("ascii") + struct.pack("<I", len(payload)) + payload
    return data + (b"\0" if len(payload) % 2 else b"")


def riff_list(list_type, *chunks):
    return chunk("LIST", list_type.encode("ascii") + b"".join(chunks))


def zstr(text, size):
    raw = text.encode("ascii")[: size - 1]
    return raw + b"\0" * (size - len(raw))


def info_string(text):
    raw = text.encode("ascii") + b"\0"
    return raw + (b"\0" if len(raw) % 2 else b"")


def soundfont(bank_name, sample_name, samples, sample_rate, loop, presets):
    """presets: [(name, bank, program)], all using the single instrument."""
    sample_count = len(samples)
    smpl = struct.pack("<%dh" % sample_count, *samples) + b"\0" * (46 * 2)  # 46 zero points after each sample

    phdr = b""
    pbag = b""
    pgen = b""
    for index, (name, bank, program) in enumerate(presets):
        phdr += zstr(name, 20) + struct.pack("<HHHIII", program, bank, index, 0, 0, 0)
        pbag += struct.pack("<HH", index, 0)
        pgen += struct.pack("<HH", 41, 0)  # instrument = 0
    phdr += zstr("EOP", 20) + struct.pack("<HHHIII", 0, 0, len(presets), 0, 0, 0)
    pbag += struct.pack("<HH", len(presets), 0)
    pgen += struct.pack("<HH", 0, 0)
    pmod = b"\0" * 10

    inst = zstr(sample_name, 20) + struct.pack("<H", 0) + zstr("EOI", 20) + struct.pack("<H", 1)
    ibag = struct.pack("<HH", 0, 0) + struct.pack("<HH", 2, 0)
    igen = struct.pack("<HH", 54, 1 if loop else 0)  # sampleModes
    igen += struct.pack("<HH", 53, 0)  # sampleID, last generator of the zone
    igen += struct.pack("<HH", 0, 0)
    imod = b"\0" * 10

    start_loop, end_loop = loop if loop else (8, sample_count - 8)
    shdr = zstr(sample_name, 20) + struct.pack("<IIIIIBbHH", 0, sample_count, start_loop, end_loop,
                                                sample_rate, 69, -4, 0, 1)
    shdr += zstr("EOS", 20) + struct.pack("<IIIIIBbHH", 0, 0, 0, 0, 0, 0, 0, 0, 0)

    info = riff_list("INFO",
                     chunk("ifil", struct.pack("<HH", 2, 4)),
                     chunk("isng", info_string("EMU8000")),
                     chunk("INAM", info_string(bank_name)),
                     chunk("ICOP", info_string("CC0 1.0, generated by tools/make-sample-sf2.py")))
    sdta = riff_list("sdta", chunk("smpl", smpl))
    pdta = riff_list("pdta", chunk("phdr", phdr), chunk("pbag", pbag), chunk("pmod", pmod), chunk("pgen", pgen),
                     chunk("inst", inst), chunk("ibag", ibag), chunk("imod", imod), chunk("igen", igen),
                     chunk("shdr", shdr))
    body = b"sfbk" + info + sdta + pdta
    return b"RIFF" + struct.pack("<I", len(body)) + body


def main(output):
    output = Path(output)
    # 441 Hz: 100 points per cycle at 44.1 kHz, 32 whole cycles, looped on cycle boundaries.
    sine = [round(math.sin(2 * math.pi * i / 100) * 16000) for i in range(3200)]
    (output).mkdir(parents=True, exist_ok=True)
    (output / "Sines.sf2").write_bytes(soundfont(
        "Soundpack Sample Sines", "Sine", sine, 44100, (100, 3100),
        [("Sine Lead", 0, 0), ("Sine Pad", 0, 1)]))
    # A short decaying 2 kHz burst, unlooped, as a drum kit (bank 128).
    click = [round(math.sin(2 * math.pi * i * 2000 / 44100) * 16000 * math.exp(-i / 200)) for i in range(2048)]
    (output / "Drums").mkdir(exist_ok=True)
    (output / "Drums" / "Clicks.sf2").write_bytes(soundfont(
        "Soundpack Sample Clicks", "Click", click, 44100, None, [("Click Kit", 128, 0)]))


if __name__ == "__main__":
    main(sys.argv[1])
